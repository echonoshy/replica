export interface DemoTurn {
  role: "user" | "assistant";
  content: string;
}

export interface DemoDayScript {
  day: number;
  id: string;
  label: string;
  tag: string;
  title: string;
  subtitle: string;
  doc_date: string;
  filename: string;
  highlights: string[];
  expected_effect: string;
  messages: DemoTurn[];
}

export interface DemoPromptPreset {
  id: string;
  badge: string;
  title: string;
  description: string;
  query: string;
}

