import type { Chat, Dataset } from "../realistic-datasets.js";

type Exchange = [kind: "signal" | "noise", user: string, assistant: string];

function chat(date: string, title: string, ...exchanges: Exchange[]): Chat {
  const messages: Chat["messages"] = [];
  const noiseMessages: number[] = [];
  for (const [kind, user, assistant] of exchanges) {
    if (kind === "noise") noiseMessages.push(messages.length, messages.length + 1);
    messages.push({ role: "user", content: user }, { role: "assistant", content: assistant });
  }
  return { date, title, messages, noiseMessages };
}

